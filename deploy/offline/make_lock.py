"""Regenerate the offline package lists (run by a maintainer, with internet).

Runs inside the pinned base image, so the resolved wheels match the Docker image
(Linux x86_64, CPython 3.14):

    docker run --rm -v "$PWD:/src" -w /src python:3.14.7-slim-trixie \
        python deploy/offline/make_lock.py

Writes:
    requirements.lock.txt       runtime, every package pinned with sha256 (used by the Dockerfile)
    requirements-dev.lock.txt   + test tools
    deploy/offline/DOWNLOAD-LIST.md   every file to fetch, with URL and sha256
"""

import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def report(requirements: str) -> list[dict]:
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "report.json"
        subprocess.run([sys.executable, "-m", "pip", "install", "--quiet", "--dry-run",
                        "--ignore-installed", "--only-binary=:all:", "--report", str(out),
                        "-r", requirements], check=True, cwd=ROOT)
        return json.loads(out.read_text())["install"]


def entries(items: list[dict]) -> list[dict]:
    rows = []
    for it in items:
        info = it["download_info"]
        rows.append({"name": it["metadata"]["name"], "version": it["metadata"]["version"],
                     "url": info["url"], "file": info["url"].rsplit("/", 1)[1],
                     "sha256": info["archive_info"]["hashes"]["sha256"]})
    return sorted(rows, key=lambda r: r["name"].lower())


def write_lock(path: Path, rows: list[dict], header: str) -> None:
    lines = [header, ""]
    for r in rows:
        lines.append(f"{r['name']}=={r['version']} \\\n    --hash=sha256:{r['sha256']}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    py = sys.version.split()[0]
    runtime = entries(report("requirements.txt"))
    dev = entries(report("requirements-dev.txt"))
    dev_only = [r for r in dev if r["file"] not in {x["file"] for x in runtime}]

    stamp = (f"# Generated by deploy/offline/make_lock.py for CPython {py}, Linux x86_64.\n"
             "# Do not edit; change requirements*.txt and regenerate.")
    write_lock(ROOT / "requirements.lock.txt", runtime, stamp)
    write_lock(ROOT / "requirements-dev.lock.txt", dev, stamp)

    def table(rows: list[dict]) -> str:
        out = ["| Package | Version | File | SHA-256 |", "|---|---|---|---|"]
        out += [f"| {r['name']} | {r['version']} | [{r['file']}]({r['url']}) | `{r['sha256']}` |"
                for r in rows]
        return "\n".join(out)

    md = f"""# Offline download list

Everything backend-iam needs from the internet, for building and running with no
internet access. Generated by `deploy/offline/make_lock.py` (CPython {py}, Linux x86_64).

The quickest way is `deploy/offline/download.sh` on any machine with internet and Docker.
It fetches all of this into `offline-bundle/` and checks every hash. To fetch by hand,
use the list below and put the files where the **Destination** column says.

## 1. Docker images

| Image | Pin | Destination | Needed for |
|---|---|---|---|
| `python:3.14.7-slim-trixie` | `sha256:51dafde81dbdb6ebde285137a295cf18a47ca95234fe388a343719cb97305b3d` | `offline-bundle/images/python-3.14.7-slim-trixie.tar` | **required**: base of the backend-iam image |
| `nginx:1.27-alpine`, saved as `backend-iam-proxy:1.27` | built by `download.sh` (`FROM nginx:1.27-alpine`) | `offline-bundle/images/backend-iam-proxy-1.27.tar` | **required** if you deploy the HTTPS proxy service |
| `postgres:17-alpine` | the version you run | `offline-bundle/images/postgres-17-alpine.tar` | optional: running the PostgreSQL tests |
| `minlag/mermaid-cli:11.4.2` | | `offline-bundle/images/mermaid-cli-11.4.2.tar` | optional: re-rendering `docs/*.mmd` |

On a machine with internet: `docker pull IMAGE` then `docker save -o FILE IMAGE`.
On the build machine: `docker load -i FILE`.

## 2. Python wheels: runtime (required, {len(runtime)} files)

Destination: `vendor/wheels/` in the repository (the Dockerfile installs only from there).

{table(runtime)}

## 3. Python wheels: tests (optional, {len(dev_only)} more files)

Destination: `vendor/wheels/`. Only needed to run the test suite in a Linux container.

{table(dev_only)}

## 4. Docker engine packages for the servers (only if they have no Docker and no apt mirror)

These depend on each server's distribution, so they aren't listed here. Use
`deploy/offline/download.sh --debs ubuntu:24.04` (with the servers' distribution and
version). It collects `docker.io` (plus `docker-cli` where that is a separate package) and
all their dependencies into `offline-bundle/debs/<distro>/`, ready for Ansible
(`backend_iam_docker_debs_dir`).

## 5. Already offline, nothing to download

- **Web UI:** no CDN, web fonts or JavaScript. All CSS is inline in the page.
- **Ansible role:** uses only `ansible.builtin` modules, so no Galaxy collections are needed.
  The control node needs `ansible-core` (already installed in your WSL).
"""
    (ROOT / "deploy/offline/DOWNLOAD-LIST.md").write_text(md, encoding="utf-8")
    print(f"runtime: {len(runtime)} wheels, dev extra: {len(dev_only)}")


if __name__ == "__main__":
    main()
